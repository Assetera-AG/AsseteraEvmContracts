#!/usr/bin/env node
// Generate a typed, bundled deployments map from the committed per-chain artifacts (ADR-0026 D4/D6).
// The JSON files are the single source of truth (also read raw by the .NET service); this inlines them into
// TypeScript so the SDK has zero runtime fs access. Local-chain artifacts (anvil 31337) are git-ignored, so a
// fresh checkout generates an empty map until a real network is deployed.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const deploymentsDir = join(here, "..", "src", "deployments");
const outFile = join(deploymentsDir, "deployments.gen.ts");

const entries = existsSync(deploymentsDir)
  ? readdirSync(deploymentsDir)
      .filter((f) => f.endsWith(".json"))
      .map((f) => JSON.parse(readFileSync(join(deploymentsDir, f), "utf8")))
      .filter((d) => d && d.chainId)
      .sort((a, b) => a.chainId - b.chainId)
  : [];

const body = entries.map((d) => `  ${d.chainId}: ${JSON.stringify(d, null, 2).replace(/\n/g, "\n  ")},`).join("\n");

const content = `// AUTO-GENERATED by scripts/gen-deployments.mjs — DO NOT EDIT.
// Inlined from src/deployments/*.json (the deployment artifacts written by the Foundry deploy script).
export const deployments = {
${body}
} as const;
`;

if (!existsSync(deploymentsDir)) mkdirSync(deploymentsDir, { recursive: true });
writeFileSync(outFile, content);
console.log(`Wrote ${outFile} (${entries.length} chain${entries.length === 1 ? "" : "s"})`);
